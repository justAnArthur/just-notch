import AppKit
import Carbon.HIToolbox
import CryptoKit

/// `clipboard` topic: a history of what the user copies. The pasteboard is
/// polled (macOS has no change notification) every 0.5 s while subscribed and
/// not paused. Concealed and transient copies (password managers) and ignored
/// apps are never recorded; password managers start on the ignore list. History
/// lives in Application Support.
@MainActor
public final class ClipboardService: NotchService {
    public let topics = ["clipboard"]
    public let methods = ["clipboard.copy", "clipboard.paste", "clipboard.delete", "clipboard.pin", "clipboard.clear", "clipboard.setPaused", "clipboard.setIgnoredApps"]
    public weak var sink: ServiceSink?

    static let interval: TimeInterval = 0.5
    /// Unpinned clips kept; pinned ones don't count.
    static let limit = 50
    static let maxText = 100_000
    private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    /// Password managers, ignored out of the box: not all of them mark every copy as concealed.
    static let defaultIgnoredApps = [
        "com.apple.Passwords", "com.apple.keychainaccess",
        "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc",
        "com.dashlane.dashlanephonefinal", "com.dashlane.Dashlane",
        "com.markmcguill.strongbox.mac",
    ]
    /// The defaults already added once, so one the user removes stays removed and a later new default is still added.
    static let seededKey = "clipboard.seededIgnoredApps"

    private let pasteboard = NSPasteboard.general
    private let folder: URL
    private var state: ClipboardState
    private var timer: Timer?
    private var subscribed = false
    private var changeCount: Int

    public init(folder: URL = ClipboardService.defaultFolder, defaults: UserDefaults = .standard) {
        self.folder = folder
        state = (try? Data(contentsOf: folder.appendingPathComponent("history.json")))
            .flatMap { try? JSONDecoder().decode(ClipboardState.self, from: $0) }
            ?? ClipboardState(clips: [], paused: false, ignoredApps: [])
        changeCount = pasteboard.changeCount
        let seeded = defaults.stringArray(forKey: Self.seededKey) ?? []
        let ignored = Self.seed(state.ignoredApps, seeded: seeded)
        if ignored != state.ignoredApps {
            state.ignoredApps = ignored
            save()
        }
        defaults.set(Self.defaultIgnoredApps, forKey: Self.seededKey)
    }

    /// The user's list plus each default not added before.
    static func seed(_ ignored: [String], seeded: [String]) -> [String] {
        ignored + defaultIgnoredApps.filter { !seeded.contains($0) && !ignored.contains($0) }
    }

    public nonisolated static var defaultFolder: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("JustNotch/clipboard", isDirectory: true)
    }

    public func start(topic: String) {
        subscribed = true
        changeCount = pasteboard.changeCount
        schedule()
    }

    public func stop(topic: String) {
        subscribed = false
        schedule()
    }

    public func snapshot(topic: String) async -> Data? {
        state.json()
    }

    public func handle(method: String, params: Data) async throws -> Data? {
        switch method {
        case "clipboard.copy":
            try copy(try clip(try decode(IdParams.self, params).id))
        case "clipboard.paste":
            let p = try decode(PasteParams.self, params)
            try copy(try clip(p.id), plain: p.plain ?? false)
            return PastedResult(pasted: await paste()).json()
        case "clipboard.delete":
            let id = try decode(IdParams.self, params).id
            change { $0.clips.removeAll { $0.id == id } }
        case "clipboard.pin":
            let p = try decode(PinParams.self, params)
            change { state in
                guard let i = state.clips.firstIndex(where: { $0.id == p.id }) else { return }
                state.clips[i].pinned = p.pinned
            }
        case "clipboard.clear":
            change { $0.clips.removeAll { !$0.pinned } }
        case "clipboard.setPaused":
            let paused = try decode(PausedParams.self, params).paused
            change { $0.paused = paused }
            changeCount = pasteboard.changeCount
            schedule()
        case "clipboard.setIgnoredApps":
            let apps = try decode(AppsParams.self, params).apps
            change { $0.ignoredApps = apps }
        default:
            throw ServiceError("unknown method \(method)")
        }
        return nil
    }

    private func schedule() {
        timer?.invalidate()
        timer = nil
        guard subscribed, !state.paused else { return }
        let timer = Timer(timeInterval: Self.interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    // MARK: recording

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.skipped) else { return }
        let source = NSWorkspace.shared.frontmostApplication
        if let id = source?.bundleIdentifier, id == Bundle.main.bundleIdentifier || state.ignoredApps.contains(id) { return }
        guard var clip = read() else { return }
        clip.app = source?.localizedName
        record(clip)
    }

    private func read() -> Clip? {
        let id = UUID().uuidString
        let now = nowMs()
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], let url = urls.first {
            let name = urls.count > 1 ? "\(url.lastPathComponent) +\(urls.count - 1)" : url.lastPathComponent
            return Clip(id: id, kind: .file, content: urls.map(\.path).joined(separator: "\n"), detail: name, copiedAt: now, pinned: false)
        }
        if let image = NSImage(pasteboard: pasteboard), pasteboard.availableType(from: [.png, .tiff]) != nil {
            return imageClip(image, id: id, at: now)
        }
        if let color = NSColor(from: pasteboard), let hex = Self.hex(color) {
            return Clip(id: id, kind: .color, content: hex, copiedAt: now, pinned: false)
        }
        guard let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return Clip(id: id, kind: Self.kind(of: text), content: String(text.prefix(Self.maxText)), copiedAt: now, pinned: false)
    }

    /// A string is a color (`#rrggbb`) or a web link when that's all it is.
    static func kind(of text: String) -> Clip.Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.range(of: #"^#[0-9a-fA-F]{6}$"#, options: .regularExpression) != nil { return .color }
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed), ["http", "https"].contains(url.scheme?.lowercased()), url.host != nil {
            return .link
        }
        return .text
    }

    static func hex(_ color: NSColor) -> String? {
        guard let rgb = color.usingColorSpace(.sRGB) else { return nil }
        let channel = { (v: CGFloat) in Int((min(max(v, 0), 1) * 255).rounded()) }
        return String(format: "#%02x%02x%02x", channel(rgb.redComponent), channel(rgb.greenComponent), channel(rgb.blueComponent))
    }

    private func imageClip(_ image: NSImage, id: String, at now: Double) -> Clip? {
        guard let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        if let existing = state.clips.first(where: { $0.kind == .image && $0.id == hash }) {
            var moved = existing
            moved.copiedAt = now
            return moved
        }
        try? FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
        guard (try? png.write(to: imageFile(hash))) != nil else { return nil }
        return Clip(
            id: hash, kind: .image, content: "\(rep.pixelsWide)×\(rep.pixelsHigh)",
            detail: ByteCountFormatter.string(fromByteCount: Int64(png.count), countStyle: .file),
            preview: Self.thumbnail(rep), copiedAt: now, pinned: false
        )
    }

    private static func thumbnail(_ rep: NSBitmapImageRep, side: CGFloat = 160) -> String? {
        let scale = min(side / CGFloat(max(rep.pixelsWide, rep.pixelsHigh)), 1)
        let size = NSSize(width: (CGFloat(rep.pixelsWide) * scale).rounded(), height: (CGFloat(rep.pixelsHigh) * scale).rounded())
        guard let small = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size.width), pixelsHigh: Int(size.height), bitsPerSample: 8,
                                           samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)
        else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: small)
        rep.draw(in: NSRect(origin: .zero, size: size))
        NSGraphicsContext.restoreGraphicsState()
        guard let png = small.representation(using: .png, properties: [:]) else { return nil }
        return "data:image/png;base64," + png.base64EncodedString()
    }

    /// Newest first; the same content copied again moves up instead of repeating.
    private func record(_ clip: Clip) {
        change { state in
            var clip = clip
            if let i = state.clips.firstIndex(where: { $0.id == clip.id || ($0.kind == clip.kind && $0.content == clip.content && clip.kind != .image) }) {
                clip.id = state.clips[i].id
                clip.pinned = state.clips[i].pinned
                state.clips.remove(at: i)
            }
            state.clips.insert(clip, at: 0)
            var unpinned = 0
            state.clips.removeAll { c in
                guard !c.pinned else { return false }
                unpinned += 1
                return unpinned > Self.limit
            }
        }
    }

    // MARK: copying back

    private func clip(_ id: String) throws -> Clip {
        guard let clip = state.clips.first(where: { $0.id == id }) else { throw ServiceError("no clip \(id)") }
        return clip
    }

    /// `plain` writes only a string: a file clip's paths instead of the files.
    private func copy(_ clip: Clip, plain: Bool = false) throws {
        pasteboard.clearContents()
        let written: Bool = switch clip.kind {
        case .text, .link, .color:
            pasteboard.setString(clip.content, forType: .string)
        case .file where plain:
            pasteboard.setString(clip.content, forType: .string)
        case .file:
            pasteboard.writeObjects(clip.content.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL })
        case .image:
            writeImage(imageFile(clip.id))
        }
        guard written else { throw ServiceError("couldn't copy the clip") }
        changeCount = pasteboard.changeCount
        var moved = clip
        moved.copiedAt = nowMs()
        record(moved)
    }

    /// PNG and TIFF both, as screenshots do: `NSImage` alone writes only TIFF, which Electron and Qt apps (Beeper,
    /// Telegram, Slack…) don't paste.
    private func writeImage(_ url: URL) -> Bool {
        guard let png = try? Data(contentsOf: url) else { return false }
        let item = NSPasteboardItem()
        item.setData(png, forType: .png)
        if let tiff = NSImage(data: png)?.tiffRepresentation { item.setData(tiff, forType: .tiff) }
        return pasteboard.writeObjects([item])
    }

    private static var askedForAccessibility = false

    /// ⌘V into the app in front, which needs Accessibility; without it, asks once per run and leaves the clip copied.
    private func paste() async -> Bool {
        guard AXIsProcessTrusted() else {
            if !Self.askedForAccessibility {
                Self.askedForAccessibility = true
                AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
            }
            return false
        }
        // The launcher has just closed: give the target app the keyboard back first.
        try? await Task.sleep(for: .milliseconds(60))
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
        return true
    }

    // MARK: state

    private var imagesFolder: URL { folder.appendingPathComponent("images", isDirectory: true) }
    private func imageFile(_ id: String) -> URL { imagesFolder.appendingPathComponent("\(id).png") }

    private func change(_ mutate: (inout ClipboardState) -> Void) {
        let before = state
        mutate(&state)
        guard state != before else { return }
        let kept = Set(state.clips.map(\.id))
        for clip in before.clips where clip.kind == .image && !kept.contains(clip.id) {
            try? FileManager.default.removeItem(at: imageFile(clip.id))
        }
        save()
        if subscribed, let data = state.json() { sink?.publish(topic: "clipboard", value: data) }
    }

    private func save() {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? state.json()?.write(to: folder.appendingPathComponent("history.json"), options: .atomic)
    }
}
